/**
 * Expo config plugin: trust Let's Encrypt's roots on old Android.
 *
 * Android only added ISRG Root X1 (Let's Encrypt) to its trust store in 7.1.1.
 * Since 2024 Let's Encrypt no longer serves the cross-signed chain old phones
 * relied on, so on Android 7.0 — e.g. the warehouse's Huawei nova plus
 * (MLA-L11) — any API host with a Let's Encrypt certificate fails with
 * "Trust anchor for certification path not found". This bundles ISRG Root X1
 * and X2 (fingerprints 96:BC:EC:06… and 69:72:9B:8E…) and tells Android to
 * trust them alongside the system store. Newer phones already trust both, so
 * nothing changes for them; nothing is trusted that a current phone doesn't.
 *
 * Only affects native builds (`npm run build:apk`); Expo Go ignores plugins.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const CERTS = ['isrg_root_x1', 'isrg_root_x2'];

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-trust-anchors.js -->
<network-security-config>
  <base-config>
    <trust-anchors>
      <certificates src="system" />
${CERTS.map((c) => `      <certificates src="@raw/${c}" />`).join('\n')}
    </trust-anchors>
  </base-config>
  <!-- A config file replaces android:usesCleartextTraffic, so keep plain HTTP to
       a local Metro server working for debug builds. Release builds load their
       bundled JavaScript and only talk HTTPS. -->
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">localhost</domain>
    <domain includeSubdomains="false">127.0.0.1</domain>
    <domain includeSubdomains="false">10.0.2.2</domain>
  </domain-config>
</network-security-config>
`;

function withTrustFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      fs.mkdirSync(path.join(res, 'raw'), { recursive: true });
      fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
      for (const c of CERTS) {
        fs.copyFileSync(path.join(__dirname, 'certs', `${c}.pem`), path.join(res, 'raw', `${c}.pem`));
      }
      fs.writeFileSync(path.join(res, 'xml', 'network_security_config.xml'), NETWORK_SECURITY_CONFIG);
      return cfg;
    },
  ]);
}

function withManifestEntry(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return cfg;
  });
}

module.exports = (config) => withManifestEntry(withTrustFiles(config));
